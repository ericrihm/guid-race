void guid_lookup16(const IID *iid, char *out)
{
    const uint8_t *p = (const uint8_t *)iid;

    // Data1: 4 bytes, big-endian output (bytes 3,2,1,0)
    memcpy(out + 0, &hex_pair[p[3]], 2);
    memcpy(out + 2, &hex_pair[p[2]], 2);
    memcpy(out + 4, &hex_pair[p[1]], 2);
    memcpy(out + 6, &hex_pair[p[0]], 2);
    out[8] = '-';

    // Data2: 2 bytes (5,4)
    memcpy(out + 9,  &hex_pair[p[5]], 2);
    memcpy(out + 11, &hex_pair[p[4]], 2);
    out[13] = '-';

    // Data3: 2 bytes (7,6)
    memcpy(out + 14, &hex_pair[p[7]], 2);
    memcpy(out + 16, &hex_pair[p[6]], 2);
    out[18] = '-';

    // Data4[0..1]: 2 bytes in order
    memcpy(out + 19, &hex_pair[p[8]], 2);
    memcpy(out + 21, &hex_pair[p[9]], 2);
    out[23] = '-';

    // Data4[2..7]: 6 bytes in order
    memcpy(out + 24, &hex_pair[p[10]], 2);
    memcpy(out + 26, &hex_pair[p[11]], 2);
    memcpy(out + 28, &hex_pair[p[12]], 2);
    memcpy(out + 30, &hex_pair[p[13]], 2);
    memcpy(out + 32, &hex_pair[p[14]], 2);
    memcpy(out + 34, &hex_pair[p[15]], 2);
    out[36] = '\0';
}
